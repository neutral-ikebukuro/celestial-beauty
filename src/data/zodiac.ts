export const DAYS_IN_MONTH = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

/** 月日から太陽星座(西洋占星術のトロピカル方式・目安日) */
export function signFromDate(month: number, day: number): number {
  const v = month * 100 + day;
  // 各星座の開始日を新しい順に比較
  const order = [...SIGNS].sort((a, b) => b.start[0] * 100 + b.start[1] - (a.start[0] * 100 + a.start[1]));
  for (const s of order) if (v >= s.start[0] * 100 + s.start[1]) return s.id;
  return 9; // 1/1〜1/19 は山羊座
}

/** 境目(開始日の前後1日)かどうか */
export function isCusp(month: number, day: number): boolean {
  return SIGNS.some((s) => {
    if (s.start[0] !== month) return false;
    return Math.abs(s.start[1] - day) <= 1;
  });
}

export function rangeLabel(id: number): string {
  const s = SIGNS[id];
  const next = SIGNS[(id + 1) % 12];
  let [m, d] = next.start;
  d -= 1;
  if (d === 0) { m = m === 1 ? 12 : m - 1; d = DAYS_IN_MONTH[m - 1]; }
  return `${s.start[0]}.${s.start[1]} — ${m}.${d}`;
}
